package restaurante.app.infraestructura.basedatos;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public final class ConexionBaseDatos {
    private static final String URL = "jdbc:h2:mem:restaurante;DB_CLOSE_DELAY=-1";
    private static final String USER = "sa";
    private static final String PASSWORD = "";

    public static Connection getConnection() throws SQLException {
        Connection connection = DriverManager.getConnection(URL, USER, PASSWORD);
        inicializarEsquema(connection);
        return connection;
    }

    private static synchronized void inicializarEsquema(Connection connection) throws SQLException {
        try (Statement st = connection.createStatement()) {
            st.execute("CREATE TABLE IF NOT EXISTS pedido (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cliente VARCHAR(255), estado VARCHAR(30) NOT NULL, fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
            st.execute("CREATE TABLE IF NOT EXISTS detalle_pedido (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_pedido BIGINT NOT NULL, id_producto BIGINT, id_menu BIGINT, cantidad INT NOT NULL CHECK (cantidad > 0), precio_unitario DECIMAL(15,2) NOT NULL, FOREIGN KEY(id_pedido) REFERENCES pedido(id))");
            st.execute("CREATE TABLE IF NOT EXISTS venta (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_pedido BIGINT UNIQUE, fecha_venta TIMESTAMP DEFAULT CURRENT_TIMESTAMP, metodo_pago VARCHAR(50), estado_pago VARCHAR(30), total DECIMAL(15,2) NOT NULL)");
            st.execute("CREATE TABLE IF NOT EXISTS detalle_venta (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_venta BIGINT NOT NULL, id_producto BIGINT, id_menu BIGINT, cantidad INT NOT NULL CHECK (cantidad > 0), precio_unitario DECIMAL(15,2) NOT NULL, subtotal DECIMAL(15,2) NOT NULL, FOREIGN KEY(id_venta) REFERENCES venta(id))");
            st.execute("CREATE TABLE IF NOT EXISTS seleccion_menu (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_detalle_pedido BIGINT, id_detalle_venta BIGINT, id_menu BIGINT, id_producto BIGINT, descripcion VARCHAR(500), cantidad INT DEFAULT 1, CHECK ((id_detalle_pedido IS NOT NULL AND id_detalle_venta IS NULL) OR (id_detalle_pedido IS NULL AND id_detalle_venta IS NOT NULL))");
        }
    }
}
